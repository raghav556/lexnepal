const BS_START_YEAR = 2000;
const AD_START = new Date(1943, 3, 14);

export type BsDate = { year: number; month: number; day: number };

export function gregorianToBs(date: Date): BsDate {
  const startMs = AD_START.getTime();
  const givenMs = new Date(date.getFullYear(), date.getMonth(), date.getDate()).getTime();
  let totalDays = Math.floor((givenMs - startMs) / 86400000);
  let bsYear = BS_START_YEAR, bsMonth = 1, bsDay = 1;
  outer: for (let y = BS_START_YEAR; y <= 2090; y++) {
    const months = BS_MONTH_DAYS[y];
    if (!months) break;
    for (let m = 0; m < 12; m++) {
      if (totalDays < months[m]) { bsYear = y; bsMonth = m + 1; bsDay = totalDays + 1; break outer; }
      totalDays -= months[m];
    }
  }
  return { year: bsYear, month: bsMonth, day: bsDay };
}

export function bsToGregorian(bs: BsDate): Date {
  let totalDays = 0;
  for (let y = BS_START_YEAR; y < bs.year; y++) {
    const months = BS_MONTH_DAYS[y];
    if (!months) break;
    totalDays += months.reduce((a, b) => a + b, 0);
  }
  const months = BS_MONTH_DAYS[bs.year];
  if (months) { for (let m = 0; m < bs.month - 1; m++) totalDays += months[m]; }
  totalDays += bs.day - 1;
  return new Date(AD_START.getTime() + totalDays * 86400000);
}

const BS_MONTHS_EN = ["Baisakh","Jestha","Ashadh","Shrawan","Bhadra","Ashwin","Kartik","Mangsir","Poush","Magh","Falgun","Chaitra"];

export function formatBs(bs: BsDate, lang: "ne" | "en" = "en"): string {
  return `${bs.day} ${BS_MONTHS_EN[bs.month - 1]} ${bs.year}`;
}

export function bsToString(bs: BsDate): string {
  return `${bs.year}-${String(bs.month).padStart(2,"0")}-${String(bs.day).padStart(2,"0")}`;
}

export function parseBsString(str: string): BsDate {
  const [y, m, d] = str.split("-").map(Number);
  return { year: y, month: m, day: d };
}

export function todayBs(): BsDate { return gregorianToBs(new Date()); }

export function formatDualDate(isoDate: string, lang: "ne" | "en" = "en"): string {
  const d = new Date(isoDate);
  const bs = gregorianToBs(d);
  const bsStr = formatBs(bs, lang);
  const adStr = d.toLocaleDateString("en-GB", { day: "2-digit", month: "short", year: "numeric" });
  return `${bsStr} (${adStr})`;
}
